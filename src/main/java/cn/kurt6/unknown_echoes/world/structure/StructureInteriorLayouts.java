    // 判定只取决于方块身份；每个线程只保留上一项，失败不能写入缓存。
    private static final ThreadLocal<DecorationCache> DECORATION_CACHE = ThreadLocal.withInitial(DecorationCache::new);
    private static final class DecorationCache {
        private Block block;
        private boolean accepted;
    }

    static boolean decoratable(BlockState state) {
        if (state == null) return uncachedDecoratable(null);
        Block block = state.getBlock();
        DecorationCache cache = DECORATION_CACHE.get();
        if (cache.block == block) return cache.accepted;
        boolean accepted = uncachedDecoratable(state);
        cache.block = block;
        cache.accepted = accepted;
        return accepted;
    }

