    static BlockState surfaceMaterial(Palette palette, char slot) {
        return switch (slot) {
            case '0' -> palette.stone();
            case '1' -> palette.trim();
            case '2' -> palette.inset();
            case '3' -> palette.glass();
            case '4' -> palette.lamp();
            case '7' -> palette.wood();
            default -> throw new IllegalArgumentException("Unknown surface material: " + slot);
        };
    }
